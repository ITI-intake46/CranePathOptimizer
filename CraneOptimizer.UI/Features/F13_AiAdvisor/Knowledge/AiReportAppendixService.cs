using System.Text;

namespace CraneOptimizer.UI.Features.F13_AiAdvisor.Knowledge
{
    public sealed class AiReportAppendixService : IAiReportAppendixService
    {
        public string BuildAppendixMarkdown(string question, string answer, string model, string contextPreview)
        {
            var builder = new StringBuilder();
            builder.AppendLine("# AI Copilot Report Appendix");
            builder.AppendLine();
            builder.AppendLine($"- Generated: {DateTimeOffset.Now:yyyy-MM-dd HH:mm:ss zzz}");
            builder.AppendLine($"- Local model: {model}");
            builder.AppendLine("- Safety mode: Advisory only; not a crane-plan certification.");
            builder.AppendLine();
            builder.AppendLine("## Question");
            builder.AppendLine();
            builder.AppendLine(question.Trim());
            builder.AppendLine();
            builder.AppendLine("## AI Explanation / Note");
            builder.AppendLine();
            builder.AppendLine(answer.Trim());
            builder.AppendLine();
            builder.AppendLine("## Mandatory Disclaimer");
            builder.AppendLine();
            builder.AppendLine("This appendix is generated by a local AI assistant from application context and deterministic diagnostics. It does not replace manufacturer load charts, project specifications, regulatory requirements, or qualified engineering review. Final crane planning decisions must be validated by responsible personnel.");
            builder.AppendLine();
            builder.AppendLine("## Auditable Context Snapshot");
            builder.AppendLine();
            builder.AppendLine("```json");
            builder.AppendLine(contextPreview.Trim());
            builder.AppendLine("```");
            return builder.ToString();
        }
    }
}
