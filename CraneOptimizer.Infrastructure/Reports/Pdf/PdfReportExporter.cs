using System.IO;
using CraneOptimizer.Application.Reports.Interfaces;
using CraneOptimizer.Application.Reports.Models;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;

namespace CraneOptimizer.Infrastructure.Reports.Pdf;

public sealed class PdfReportExporter : IReportExporter
{
    private readonly IReportValueFormatter _formatter;
    private readonly PdfExportOptions _options;

    static PdfReportExporter()
    {
        QuestPDF.Settings.License = LicenseType.Community;
    }

    public PdfReportExporter(IReportValueFormatter formatter)
        : this(formatter, new PdfExportOptions())
    {
    }

    public PdfReportExporter(IReportValueFormatter formatter, PdfExportOptions options)
    {
        _formatter = formatter;
        _options = options;
    }

    public ReportFormat Format => ReportFormat.Pdf;

    public async Task<ReportExportResult> ExportAsync(
        ReportDocument document,
        string outputPath,
        CancellationToken cancellationToken = default)
    {
        cancellationToken.ThrowIfCancellationRequested();

        var fullPath = Path.GetFullPath(outputPath);
        var directory = Path.GetDirectoryName(fullPath);

        if (!string.IsNullOrWhiteSpace(directory))
            Directory.CreateDirectory(directory);

        await Task.Run(() =>
        {
            cancellationToken.ThrowIfCancellationRequested();

            Document.Create(container => ComposeDocument(container, document, cancellationToken))
                .GeneratePdf(fullPath);
        }, cancellationToken).ConfigureAwait(false);

        return ReportExportResult.Ok(fullPath);
    }

    private void ComposeDocument(IDocumentContainer container, ReportDocument document, CancellationToken cancellationToken)
    {
        container.Page(page =>
        {
            page.Margin(36);
            page.Size(PageSizes.A4);
            page.DefaultTextStyle(style => style.FontFamily(_options.Theme.FontFamily).FontSize(9));

            page.Header().Element(header => ComposeHeader(header, document));
            page.Content().PaddingVertical(12).Column(column =>
            {
                foreach (var section in document.Sections)
                {
                    cancellationToken.ThrowIfCancellationRequested();
                    column.Item().Element(item => ComposeSection(item, section));
                    column.Item().PaddingBottom(10);
                }
            });
            page.Footer().AlignCenter().Text(text =>
            {
                text.Span("Generated by Mobile Crane Path Optimizer | Page ");
                text.CurrentPageNumber();
                text.Span(" of ");
                text.TotalPages();
            });
        });
    }

    private void ComposeHeader(IContainer container, ReportDocument document)
    {
        container.Column(column =>
        {
            column.Item().Text(document.Title)
                .FontSize(18)
                .Bold()
                .FontColor(_options.Theme.PrimaryColorHex);

            column.Item().PaddingTop(6).Table(table =>
            {
                table.ColumnsDefinition(columns =>
                {
                    columns.RelativeColumn();
                    columns.RelativeColumn();
                });

                AddMetadataCell(table, "Project", document.Metadata.ProjectName);
                AddMetadataCell(table, "IFC File", document.Metadata.IfcFileName);
                AddMetadataCell(table, "Crane", document.Metadata.CraneName);
                AddMetadataCell(table, "Created UTC", document.CreatedAtUtc.ToUniversalTime().ToString("yyyy-MM-dd HH:mm:ss"));
            });

            column.Item().PaddingTop(8).LineHorizontal(1).LineColor(_options.Theme.SecondaryColorHex);
        });
    }

    private void ComposeSection(IContainer container, ReportSection section)
    {
        container.Column(column =>
        {
            column.Item().Text(section.Title)
                .FontSize(13)
                .Bold()
                .FontColor(_options.Theme.PrimaryColorHex);

            if (!string.IsNullOrWhiteSpace(section.Description))
                column.Item().PaddingTop(2).Text(section.Description).FontColor(Colors.Grey.Darken1);

            if (section.Metrics.Count > 0)
                column.Item().PaddingTop(8).Element(item => ComposeMetrics(item, section.Metrics));

            foreach (var note in section.Notes)
                column.Item().PaddingTop(6).Text(note).Italic().FontColor(Colors.Grey.Darken2);

            foreach (var table in section.Tables)
                column.Item().PaddingTop(8).Element(item => ComposeTable(item, table));
        });
    }

    private static void ComposeMetrics(IContainer container, IReadOnlyList<ReportMetric> metrics)
    {
        container.Table(table =>
        {
            table.ColumnsDefinition(columns =>
            {
                columns.RelativeColumn();
                columns.RelativeColumn();
            });

            foreach (var metric in metrics)
            {
                table.Cell().BorderBottom(0.5f).BorderColor(Colors.Grey.Lighten2).Padding(4).Text(metric.Label).SemiBold();
                table.Cell().BorderBottom(0.5f).BorderColor(Colors.Grey.Lighten2).Padding(4).Text(
                    string.IsNullOrWhiteSpace(metric.Unit) ? metric.Value : $"{metric.Value} {metric.Unit}");
            }
        });
    }

    private void ComposeTable(IContainer container, ReportTable reportTable)
    {
        var rows = reportTable.Rows.Take(_options.MaxRowsPerTable).ToList();
        var isTruncated = reportTable.Rows.Count > rows.Count;

        container.Column(column =>
        {
            column.Item().Text(reportTable.Title).Bold();
            column.Item().PaddingTop(4).Table(table =>
            {
                table.ColumnsDefinition(columns =>
                {
                    foreach (var _ in reportTable.Columns)
                        columns.RelativeColumn();
                });

                foreach (var reportColumn in reportTable.Columns)
                    table.Cell().Background(Colors.Grey.Lighten3).Padding(3).Text(BuildHeader(reportColumn)).SemiBold().FontSize(7);

                foreach (var row in rows)
                {
                    foreach (var reportColumn in reportTable.Columns)
                    {
                        row.Values.TryGetValue(reportColumn.Key, out var value);
                        table.Cell().BorderBottom(0.25f).BorderColor(Colors.Grey.Lighten2).Padding(3).Text(_formatter.FormatValue(value, reportColumn)).FontSize(7);
                    }
                }
            });

            if (isTruncated && _options.AddTruncationNote)
            {
                column.Item().PaddingTop(4).Text("Large table truncated in PDF. Full data is available in CSV export.")
                    .Italic()
                    .FontColor(Colors.Grey.Darken2);
            }
        });
    }

    private static void AddMetadataCell(TableDescriptor table, string label, string value)
    {
        table.Cell().PaddingBottom(2).Text($"{label}: {value}");
    }

    private static string BuildHeader(ReportColumn column)
    {
        return string.IsNullOrWhiteSpace(column.Unit)
            ? column.Header
            : $"{column.Header} ({column.Unit})";
    }
}
